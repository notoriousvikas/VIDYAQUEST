let defaultsSeededPromise: Promise<void> | null = null;

export async function ensureStudentDefaultsSeeded(): Promise<void> {
  if (!defaultsSeededPromise) {
    defaultsSeededPromise = (async () => {
      const [itemCount, achCount] = await Promise.all([
        AvatarItemModel.countDocuments({}),
        AchievementModel.countDocuments({}),
      ]);

      if (itemCount >= AVATAR_ITEM_CATALOG.length && achCount >= ACHIEVEMENT_CATALOG.length) {
        return;
      }

      await Promise.all([
        ...AVATAR_ITEM_CATALOG.map((item) =>
          AvatarItemModel.updateOne(
            { itemKey: item.itemKey },
            { $setOnInsert: { ...item, isActive: true } },
            { upsert: true },
          ),
        ),
        ...ACHIEVEMENT_CATALOG.map((ach) =>
          AchievementModel.updateOne(
            { code: ach.code },
            { $setOnInsert: { ...ach, isActive: true } },
            { upsert: true },
          ),
        ),
      ]);
    })().catch((err) => {
      defaultsSeededPromise = null;
      throw err;
    });
  }
  return defaultsSeededPromise;
}
